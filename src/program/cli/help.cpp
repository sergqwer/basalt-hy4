#include "help.hpp"

#include "basalt/log.hpp"
#include "basalt/program/options.hpp"

namespace basalt::program::cli {

void usage() {
    basalt::log::raw("basalt serve --config FILE [--python PY] [--server python|rust] [server args...]\n"
                 "basalt serve MODEL.basalt [--python PY] [--server python|rust] [server args...]\n"
                 "    runs the server over this binary - the Python one (serve/, the default) or, with --server rust, its\n"
                 "    Rust port (basalt-serve beside this binary or in serve-rs/target/{release,debug}); it takes the same\n"
                 "    arguments. The server reads its options and the engine flags\n"
                 "    from the config file and the command line (the model is the config's or MODEL.basalt, which stands\n"
                 "    for --model); --python defaults to .venv/bin/python in the source tree, else python3; the other\n"
                 "    arguments go to the server.  It runs in the source tree; --model and --config paths are made absolute.\n"
                 "    A model file that is missing is fetched from Hugging Face first (the config entry\'s \"hf\", or a\n"
                 "    known pack name; tools/get_model.py); --no-download, or \"download\": false in the entry, turns that off.\n"
                 "basalt download [OWNER/REPO/FILE | PACK-NAME] [--dir models]\n"
                 "    fetches a model pack ahead (default: the Hy4-flash GPTQ pack), checked against the repo\'s size and hash\n"
                 "basalt generate --model FILE.basalt --tokens \"1,2,3\" [options]\n"
                 "\n"
                 "  --model FILE         the .basalt model file (required): the dense weights, experts, source tensors\n"
                 "                       (embedding, PLE table, native projections, head), draft layer and 8-bit\n"
                 "                       hyper-connection copies all come from it; the expert profile from\n"
                 "                       --expert-profile, else data/profiles\n"
                 "  --expert-profile P   the expert profile to place at start (the format of data/profiles)\n"
                 "                       instead of the engine's own for the model\n"
                 "  --tokens LIST        the prompt as comma-separated token IDS (required)\n"
                 "  --tokens-file PATH   pretokenized prompt, commas or whitespace (alternative to --tokens)\n"
                 "  --kv fp16|fp8        KV storage of the attention caches: fp16 (default) or fp8\n"
                 "                       (docs/models/hy4-flash.md)\n"
                 "  --serve              stay resident and take requests on stdin (the server's mode)\n"
                 "  --exp NAME=VALUE[,...]  diagnostics; concur9_logit_hash=1 prints a hash of each accepted row's\n"
                 "                       logits on stderr\n"
                 "  --gpu A,B,..|auto    the GPUs to use, as nvidia-smi numbers them (within CUDA_VISIBLE_DEVICES when\n"
                 "                       set): exactly these, the first the main card; the engine gives the rest their\n"
                 "                       roles.  auto = every Blackwell card, the fastest as main.  Default: GPU 0 alone\n"
                 "  --gpu-plan           print the --gpu choice as one JSON line and exit (no model needed)\n"
                 "  --stop-eos           stop when the model emits an end-of-turn token\n"
                 "  --eos-ids LIST       the end-of-turn token ids for --stop-eos (default the pack's); implies it\n"
                 "  --prompt-cache-root N  --serve: checkpoint a prompt's first turn boundary when it is at least N tokens\n"
                 "                       long (default 2048, 0 = never)\n"
                 "  --max-new N          tokens to generate (default 16)\n"
                 "  --max-context N      KV/state capacity (default %lld)\n"
                 "  --greedy             argmax (the default)\n"
                 "  --seed S             enable sampling with this Philox seed\n"
                 "  --top-k N --top-p F --temperature F\n"
                 "  --vision             --serve takes images and videos, encoded in this process (it reads the model\n"
                 "                       file's vision/mmproj in place): ENC and ENCV requests borrow expert-cache slots\n"
                 "                       for the encoder and give them back refilled\n"
                 "  --vision-external    --serve takes images whose embeddings come from basalt-vision --model FILE\n"
                 "                       (GENI requests)\n"
                 "  --prompt-cache N     --serve: keep N conversation checkpoints between requests (default 6, ~118 MB\n"
                 "                       of RAM each; 0 = read every prompt from the start)\n"
                 "  --conversation-cache-mib N  --serve: RAM budget for parked conversations (default 0 = off)\n"
                 "  --conversation-cache-slots N  --serve: at most N parked conversations (default 4)\n"
                 "  --conversation-cache-min-free-mib N  --serve: physical RAM floor when parking (default 2560); below\n"
                 "                       it the parked conversations give RAM back, oldest first\n"
                 "  --ram-reserve-mib N  RAM left free for the rest of the system (default 2048); the expert tiers leave\n"
                 "                       it and the --serve RAM guard holds it (0 = keep nothing, guard off)\n"
                 "  --conversation-cache-min-tokens N  --serve: park only conversations of at least N tokens (default 0 = park every one)\n"
                 "  --conversation-cache-disk-mib N  --serve: park conversations on disk, at most N MiB, and read them back\n"
                 "                       when a prompt starts with one, also after a restart (default 0 = off)\n"
                 "  --conversation-cache-dir DIR  --serve: the disk tier's folder (required with a budget unless the\n"
                 "                       server starts the engine, which uses the model cache folder)\n"
                 "  --batch N / --slots N  --serve (opt-in): up to N requests decode together in batch slots (2..8),\n"
                 "                       each slot with its own session (VRAM like the main one)\n"
                 "  --turn-token ID      --serve: the token that opens a chat turn (default the pack's)\n"
                 "  --tail-role-token ID --serve: a turn of this role right before the last turn is left out of\n"
                 "                       the conversation checkpoint (a trailing effort turn; default -1 = off)\n"
                 "  --spec N             speculative decoding: verify windows of at most N tokens (the last accepted\n"
                 "                       token plus up to N-1 drafts); 0 or 1 = no speculation (default: 6 with the\n"
                 "                       pack's DFly2 drafter, 0 without a drafter)\n"
                 "  --route-tail-skip [R]  MoE models: a decode window drops a routed expert no GPU holds when every\n"
                 "                       entry naming it ranks R or lower by router weight (0-based of the model's k):\n"
                 "                       neither copied nor computed, the others keep their weights.  Faster, but LESS\n"
                 "                       ACCURATE than the model (docs/precision/quality.md#lossy-routing-flags).\n"
                 "                       R in 1..k-1, lower drops more; the flag alone = k-1.  Default off (exact)\n"
                 "  --route-prior [LAMBDA]  MoE models: a decode window picks its k experts as if each one a GPU holds\n"
                 "                       had LAMBDA added to its router logit; the weights stay the router's.  Faster, but\n"
                 "                       LESS ACCURATE than the model (docs/precision/quality.md#lossy-routing-flags).\n"
                 "                       LAMBDA in (0, 16], higher routes harder toward held experts; the flag alone = 0.5.\n"
                 "                       Default off (exact)\n"
                 "  --grammar on|off     --serve: enforce a request's \"grammar\" (tool-call, JSON-schema or JSON-object\n"
                 "                       grammar) on the sampled tokens; the vocabulary comes from the pack.  Default off\n"
                 "  --draft-log FILE     one line per decode window for draft-policy study\n"
                 "  --ppl-base FILE      llama.cpp KL-divergence base for ppl= requests\n"
                 "  --ppl-out FILE       where ppl= requests write their per-row lines\n"
                 "  --expert-cache N|auto  keep N expert blobs resident in VRAM and compute their rows on the\n"
                 "                       GPU.  Default auto with an expert profile.  auto = as many as fit in the VRAM\n"
                 "                       left after the weights, the session and --vram-reserve-mib\n"
                 "  --vram-reserve-mib N  VRAM left free on the primary GPU for graphs, scratch and the head when\n"
                 "                       --expert-cache auto sizes the tier and the KV grows (default 700; at least 256).\n"
                 "                       On Windows a model adapter keeps 700 MiB free unless this is given: with less,\n"
                 "                       WDDM pages GPU memory out to RAM instead of refusing it, and the kernels slow down\n"
                 "  --peer-reserve-mib N  VRAM the peer tier leaves free on its card (default 600)\n"
                 "  --pool-workers N     CPU expert pool worker count.  Auto when not set: every physical core\n"
                 "                       except the one the host loop spins on (on a hybrid CPU, with --pool-affinity\n"
                 "                       auto: P-cores minus 1 plus half the E-cores; p-cores: P-cores minus 1),\n"
                 "                       lowered so the workers and the host thread fit a cgroup CPU quota\n"
                 "                       (container CPU limit).\n"
                 "  --pool-affinity MODE Which cores size the worker pool (workers are not pinned): all (one\n"
                 "                       worker per physical core), auto (hybrid CPUs: the P-cores minus the\n"
                 "                       host's, plus half the E-cores) or p-cores (the P-cores minus the host's).\n"
                 "                       Auto when not set.\n"
                 "  --resident-budget-gib N  the resident mode with at most N GiB of experts in RAM (hottest first;\n"
                 "                       auto when not set: what fits);\n"
                 "                       a budget that would leave less than the RAM floor free is refused, naming\n"
                 "                       the largest safe value.\n", (long long) basalt::program::kDefaultContext);
}

}  // namespace basalt::program::cli
